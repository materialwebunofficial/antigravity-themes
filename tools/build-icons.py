"""Builds themes/md3e-icons.css: the app's icons swapped for Material Symbols Rounded.

Antigravity draws its icons as React components, one per Material Symbol
(`AddIcon`, `ChevronRightIcon`, ...), each an <svg viewBox="0 -960 960 960">
with the symbol's path. Material Symbols fonts use the same 960-unit grid, so
a glyph from the Rounded font drops into the same <path> unchanged: the CSS
`d` property replaces the geometry, matched by the app's own path string.
No DOM changes, masks or icon font text.

Glyphs come from the md3e-web package's variable Material Symbols Rounded font
(Apache-2.0), read at FILL 0, GRAD 0, opsz 20 (the app draws icons at 14-16px)
and wght 400.

    python -I tools/build-icons.py <app main.js> <material-symbols-rounded.full.woff2>

main.js is the app's UI bundle (the page's script, e.g. saved from the
running app over the debug port).
"""

import re
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

AXES = {"FILL": 0, "GRAD": 0, "opsz": 20, "wght": 400}
OUT = Path(__file__).resolve().parent.parent / "themes" / "md3e-icons.css"

# App component names whose symbol was renamed in the current font
RENAMES = {"FileDownload": "download", "Feedback": "chat_error", "Smartphone": "mobile"}
# Paths are matched by a prefix this long at least (and longer when another
# path in the bundle shares it): halves the stylesheet against exact matches
MIN_PREFIX = 40


def snake(name):
    s = re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Za-z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return s.lower()


def candidates(component):
    base = RENAMES.get(component) or snake(component)
    names = [base, base.replace("_", ""), re.sub(r"_(?=\d)", "", base)]
    for suffix in ("_filled", "_fill"):
        if base.endswith(suffix):
            names.insert(0, base[: -len(suffix)] + ".fill")
    return names


def app_icons(bundle):
    """[(component, [path d, ...])] for every viewBox 0 -960 960 960 icon component."""
    icons = []
    for m in re.finditer(r'(\w+)\.displayName="(\w+)Icon"', bundle):
        start = bundle.rfind('createElement("svg"', 0, m.start())
        body = bundle[start : m.start()]
        if start < 0 or "0 -960 960 960" not in body:
            continue
        paths = re.findall(r'\bd:"([^"]+)"', body)
        if paths:
            icons.append((m.group(2), paths))
    return icons


def selector(d, all_paths):
    """path[d^=...] with the shortest prefix no other bundle path starts with."""
    others = [p for p in all_paths if p != d]
    for n in range(MIN_PREFIX, len(d)):
        if not any(p.startswith(d[:n]) for p in others):
            return f'path[d^="{d[:n]}"]'
    return f'path[d="{d}"]'


def fmt(v):
    # whole units: one unit is 1/60 px at 16px, and the file shrinks by a third
    return str(round(v))


def main(bundle_path, font_path):
    bundle = Path(bundle_path).read_text(encoding="utf-8")
    all_paths = set(re.findall(r'\bd:"([^"]+)"', bundle))
    font = TTFont(font_path)
    glyphs = font.getGlyphSet(location=AXES)

    rules, missing, seen = [], [], {}
    for component, paths in app_icons(bundle):
        name = next((n for n in candidates(component) if n in glyphs), None)
        if not name:
            missing.append(component)
            continue
        pen = SVGPathPen(glyphs, ntos=fmt)
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))   # font y-up -> svg y-down
        rounded = pen.getCommands()
        for i, d in enumerate(paths):
            if seen.setdefault(d, name) != name:
                continue   # the same path in two different icons: leave it alone
            value = f'path("{rounded}")' if i == 0 else "none"
            rules.append(f':root[data-agy-theme="md3e"] {selector(d, all_paths)} {{ d: {value}; }}')

    header = (
        "/* GENERATED by tools/build-icons.py — do not edit.\n"
        "   The app's Material Symbols paths swapped for Material Symbols Rounded\n"
        f"   ({', '.join(f'{k} {v}' for k, v in AXES.items())}) from @materialwebunofficial/md3e-web\n"
        f"   (Apache-2.0). {len(rules)} paths; not in the font: {', '.join(missing) or 'none'}. */\n"
    )
    OUT.write_text(header + "\n".join(rules) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(rules)} paths, {OUT.stat().st_size // 1024} KB; missing: {missing}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
