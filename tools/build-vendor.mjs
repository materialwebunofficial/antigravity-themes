// Builds vendor/md3e/components.js from @materialwebunofficial/md3e-web: the
// package's own <md-loading-indicator>, <md-progress-indicator> and <md-menu>
// (its AndroidX LoadingIndicator / ProgressIndicator / DropdownMenu ports)
// with every module they import, as one classic script, so they can ride in
// the page script the injector evaluates (no module loader there).
// Each module keeps its own scope: it runs in a function that returns its
// exports, and its imports become destructuring of those. Sources are
// otherwise unchanged (comments and license headers kept); only named
// imports and exports are supported, anything else stops the build.
//
//   node tools/build-vendor.mjs <path-to-md3e-web-package>
//
// The output is committed; the theme needs no package at runtime.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = process.argv[2];
if (!pkg) throw new Error('usage: node tools/build-vendor.mjs <path-to-md3e-web-package>');
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const src = path.join(pkg, 'src');
const meta = JSON.parse(readFileSync(path.join(pkg, 'package.json'), 'utf8'));

const ENTRIES = ['components/md-loading-indicator.js', 'components/md-progress-indicator.js', 'components/md-menu.js'];

const IMPORT = /^\s*import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?/gm;
const REEXPORT = /^\s*export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?/gm;
const key = (file) => path.relative(src, file).replace(/\\/g, '/');

// Depth-first: every module comes after the modules it imports
const order = [];
const seen = new Set();
function visit(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const text = readFileSync(file, 'utf8');
  for (const m of [...text.matchAll(IMPORT), ...text.matchAll(REEXPORT)]) visit(path.resolve(path.dirname(file), m[2]));
  order.push(file);
}
for (const entry of ENTRIES) visit(path.join(src, entry));

const modules = order.map((file) => {
  let text = readFileSync(file, 'utf8');
  const imports = [];
  const declared = new Set();   // local names the imports bind
  const local = (n) => n.replace(/^[\w$]+\s+as\s+([\w$]+)$/, '$1');
  text = text.replace(IMPORT, (_, names, from) => {
    const list = names.split(',').map((n) => n.trim()).filter(Boolean);
    list.forEach((n) => declared.add(local(n)));
    const bindings = list.map((n) => n.replace(/^([\w$]+)\s+as\s+([\w$]+)$/, '$1: $2'));
    imports.push(`const { ${bindings.join(', ')} } = __md3e[${JSON.stringify(key(path.resolve(path.dirname(file), from)))}];`);
    return '';
  });
  if (/^\s*import\b/m.test(text)) throw new Error(`${key(file)}: unsupported import form`);
  const exports = [];
  // export { a, b } from './x.js': an import plus an export of the same names
  // (a name the module also imports is bound once)
  text = text.replace(REEXPORT, (_, names, from) => {
    const list = names.split(',').map((n) => n.trim()).filter(Boolean);
    const fresh = list.filter((n) => !declared.has(local(n)));
    fresh.forEach((n) => declared.add(local(n)));
    if (fresh.length) imports.push(`const { ${fresh.map((n) => n.replace(/^([\w$]+)\s+as\s+([\w$]+)$/, '$1: $2')).join(', ')} } = __md3e[${JSON.stringify(key(path.resolve(path.dirname(file), from)))}];`);
    exports.push(...list.map(local));
    return '';
  });
  text = text.replace(/^export\s+((?:async\s+)?function\*?|const|let|var|class)\s+([\w$]+)/gm, (_, kind, name) => {
    exports.push(name);
    return `${kind} ${name}`;
  });
  text = text.replace(/^export\s*\{([^}]*)\}\s*;?/gm, (_, names) => {
    exports.push(...names.split(',').map((n) => n.trim()).filter(Boolean).map((n) => n.replace(/^([\w$]+)\s+as\s+([\w$]+)$/, '$2: $1')));
    return '';
  });
  if (/^export\b/m.test(text)) throw new Error(`${key(file)}: unsupported export form`);
  return `// ---- ${key(file)} ----
__md3e[${JSON.stringify(key(file))}] = (() => {
${imports.join('\n')}
${text.trim()}
return { ${exports.join(', ')} };
})();
`;
});

const out = `// GENERATED by tools/build-vendor.mjs — do not edit.
// ${meta.name} ${meta.version} (${meta.license}); see vendor/md3e/NOTICE.
// Defines <md-loading-indicator>, <md-progress-indicator> and <md-menu>
// (with <md-menu-group>, <md-menu-item>) once per page (the components guard
// their own customElements.define).
(() => {
'use strict';
const __md3e = {};
${modules.join('\n')}
})();
`;
writeFileSync(path.join(root, 'vendor', 'md3e', 'components.js'), out);
console.log(JSON.stringify({ modules: order.map(key), bytes: out.length }));
